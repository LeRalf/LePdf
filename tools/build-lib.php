$new = $root . '/lib.new';
rrmdir($tmp);
rrmdir($new);
mkdir($tmp, 0775, true);
mkdir($new, 0775, true);

$rows = [];
foreach ($packages as $name => $p) {
	echo "Fetching $name {$p['tag']} ...\n";
	$dir = $tmp . '/' . $name;
	run('git clone --quiet --depth 1 --branch ' . escapeshellarg($p['tag']) . ' ' . escapeshellarg("https://github.com/{$p['repo']}.git") . ' ' . escapeshellarg($dir));

	foreach ($p['copy'] as $rule) {
		copyDir($dir . '/' . $rule[0], $new . '/' . $rule[1], isset($rule[2]) ? $rule[2] : null);
	}
	if (isset($p['licenseFile'])) {
		if (!is_dir($new . '/licenses')) mkdir($new . '/licenses', 0775, true);
		if (!copy($dir . '/' . $p['licenseFile'][0], $new . '/licenses/' . $p['licenseFile'][1])) fail("license file missing for $name");
	}
	$rows[] = sprintf('| `%s` | %s | %s | %s |', $name, "[{$p['repo']}](https://github.com/{$p['repo']})", ltrim($p['tag'], 'v'), $p['license']);
}

file_put_contents($new . '/autoload.php', $autoload);

