$autoload = <<<'AUTOLOAD'
<?php
/**
 * Minimal PSR-4 autoloader for the libraries bundled with LePdf.
 * Every namespace maps to the folder of the same name below lib/ (Mpdf\Mpdf -> lib/Mpdf/Mpdf.php).
 * No Composer needed. See THIRD-PARTY.md for versions and licenses.
 * Generated by tools/build-lib.php, do not edit by hand.
 */

(function () {
	$base = __DIR__ . '/';
	$roots = ['Mpdf\\', 'DeepCopy\\', 'setasign\\Fpdi\\', 'Psr\\Log\\', 'Psr\\Http\\Message\\'];

	spl_autoload_register(function ($class) use ($base, $roots) {
		foreach ($roots as $root) {
			if (strpos($class, $root) === 0) {
				$file = $base . str_replace('\\', '/', $class) . '.php';
				if (is_file($file)) {
					require $file;
				}
				return;
			}
		}
	});

	// function files (both are guarded with function_exists)
	require_once $base . 'Mpdf/functions.php';
	require_once $base . 'DeepCopy/deep_copy.php';
})();

AUTOLOAD;

/* ---------- helpers ---------- */

function fail($msg) {
	fwrite(STDERR, "ERROR: $msg\n");
	exit(1);
}

function run($cmd) {
	exec($cmd . ' 2>&1', $out, $code);
	if ($code !== 0) fail("command failed: $cmd\n" . implode("\n", $out));
	return $out;
}

function rrmdir($dir) {
	if (!is_dir($dir)) return;
	foreach (scandir($dir) as $f) {
		if ($f === '.' || $f === '..') continue;
		$p = $dir . '/' . $f;
		if (is_dir($p) && !is_link($p)) rrmdir($p);
		else { @chmod($p, 0666); unlink($p); }
	}
	rmdir($dir);
}

function copyDir($from, $to, $glob = null) {
	if (!is_dir($from)) fail("source folder not found: $from");
	if (!is_dir($to) && !mkdir($to, 0775, true)) fail("cannot create $to");
	foreach (scandir($from) as $f) {
		if ($f === '.' || $f === '..' || $f === '.git') continue;
		$src = $from . '/' . $f;
		if (is_dir($src)) {
			if ($glob === null) copyDir($src, $to . '/' . $f);
		} else {
			if ($glob !== null && !fnmatch($glob, $f)) continue;
			if (!copy($src, $to . '/' . $f)) fail("cannot copy $src");
		}
	}
}

function countFiles($dir) {
	$n = 0;
	foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS)) as $f) $n++;
	return $n;
}

function latestTag($repo, $series) {
	$lines = run('git ls-remote --tags --refs ' . escapeshellarg("https://github.com/$repo.git"));
	$best = null;
	foreach ($lines as $line) {
		if (!preg_match('#refs/tags/(.+)$#', $line, $m)) continue;
		$tag = $m[1];
		if (!preg_match('/^v?\d+(\.\d+)*$/', $tag)) continue; // stable tags only
		if (!preg_match($series, $tag)) continue;
		if ($best === null || version_compare(ltrim($tag, 'v'), ltrim($best, 'v'), '>')) $best = $tag;
	}
	return $best;
}

/* ---------- check mode ---------- */

if (in_array('--check', $argv, true)) {
	$newer = 0;
	foreach ($packages as $name => $p) {
		$latest = latestTag($p['repo'], $p['series']);
		$status = ($latest === null) ? 'no tag found' : ($latest === $p['tag'] ? 'up to date' : 'NEWER: ' . $latest);
		if ($latest !== null && $latest !== $p['tag']) $newer++;
		printf("%-28s pinned %-8s %s\n", $name, $p['tag'], $status);
	}
	echo $newer ? "\n$newer package(s) have newer tags in their allowed series. Check their PHP requirement, then change 'tag' in this file and rebuild.\n" : "\nNothing to update within the allowed series.\n";
	echo "Note: newer major series that need PHP 8 are not shown on purpose (see 'series').\n";
	exit(0);
}

/* ---------- build mode ---------- */

